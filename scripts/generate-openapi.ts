import './zodOpenApi'
import { writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { OpenApiGeneratorV3, OpenAPIRegistry } from '@asteasolutions/zod-to-openapi'
import { z } from 'zod'
import { formSettingsSchema, getFormSettingsParamsSchema, updateFormSettingsRequestSchema } from '~/models/formSettings'
import { FORM_SETTINGS_ROUTE, TASK_ROUTE, TASKS_ROUTE } from '~/routes'
import {
  bulkDeleteTasksRequestSchema,
  createTaskRequestSchema,
  getTaskParamsSchema,
  getTasksParamsSchema,
  getTasksQuerySchema,
  taskSchema,
  updateTaskRequestSchema
} from '~/models/task'

const errorSchema = z.object({ error: z.string() })
const validationErrorSchema = errorSchema.extend({
  issues: z.array(z.object({ path: z.string(), message: z.string() })).optional()
})
const taskPageSchema = z.object({
  items: z.array(taskSchema),
  page: z.number().int(),
  pageSize: z.number().int(),
  total: z.number().int()
})

const json = <T extends z.ZodTypeAny>(schema: T) => ({ content: { 'application/json': { schema } } })
const validationError = { description: 'Invalid input', ...json(validationErrorSchema) }
const notFound = { description: 'Not found', ...json(errorSchema) }

const registry = new OpenAPIRegistry()
const tasks = `/${TASKS_ROUTE}`
const task = `/${TASK_ROUTE}`
const formSettings = `/${FORM_SETTINGS_ROUTE}`

registry.registerPath({
  method: 'get',
  path: tasks,
  summary: 'List tasks',
  description: 'Newest first. Search and filters are combined with AND.',
  request: { params: getTasksParamsSchema, query: getTasksQuerySchema },
  responses: { 200: { description: 'A page of tasks', ...json(taskPageSchema) }, 400: validationError }
})
registry.registerPath({
  method: 'post',
  path: tasks,
  summary: 'Create a task',
  description: 'The id is generated by the server.',
  request: { params: getTasksParamsSchema, body: { required: true, ...json(createTaskRequestSchema) } },
  responses: { 201: { description: 'The created task', ...json(taskSchema) }, 400: validationError }
})
registry.registerPath({
  method: 'delete',
  path: tasks,
  summary: 'Delete several tasks',
  description: 'Ids that do not exist are ignored.',
  request: { params: getTasksParamsSchema, body: { required: true, ...json(bulkDeleteTasksRequestSchema) } },
  responses: { 204: { description: 'Deleted' }, 400: validationError }
})
registry.registerPath({
  method: 'get',
  path: task,
  summary: 'Get a task',
  request: { params: getTaskParamsSchema },
  responses: { 200: { description: 'The task', ...json(taskSchema) }, 400: validationError, 404: notFound }
})
registry.registerPath({
  method: 'patch',
  path: task,
  summary: 'Update a task',
  description:
    'Only the fields sent are changed. Send null for dueDate or priority to clear them. customFields replaces the whole object.',
  request: { params: getTaskParamsSchema, body: { required: true, ...json(updateTaskRequestSchema) } },
  responses: { 200: { description: 'The updated task', ...json(taskSchema) }, 400: validationError, 404: notFound }
})
registry.registerPath({
  method: 'delete',
  path: task,
  summary: 'Delete a task',
  request: { params: getTaskParamsSchema },
  responses: { 204: { description: 'Deleted' }, 400: validationError, 404: notFound }
})
registry.registerPath({
  method: 'get',
  path: formSettings,
  summary: 'Get the form settings',
  description:
    'Returns the defaults if none were saved. Built-in fields missing from the saved settings are appended as their own rows.',
  request: { params: getFormSettingsParamsSchema },
  responses: { 200: { description: 'The form settings', ...json(formSettingsSchema) }, 400: validationError }
})
registry.registerPath({
  method: 'put',
  path: formSettings,
  summary: 'Replace the form settings',
  request: { params: getFormSettingsParamsSchema, body: { required: true, ...json(updateFormSettingsRequestSchema) } },
  responses: { 200: { description: 'The saved form settings', ...json(formSettingsSchema) }, 400: validationError }
})
registry.registerPath({
  method: 'delete',
  path: formSettings,
  summary: 'Reset the form settings to the defaults',
  request: { params: getFormSettingsParamsSchema },
  responses: { 204: { description: 'Reset' }, 400: validationError }
})

const document = new OpenApiGeneratorV3(registry.definitions).generateDocument({
  openapi: '3.0.3',
  info: { title: 'Kitameraki Task API', version: '1.0.0', description: 'Task management API with per-organization form settings.' },
  servers: [{ url: 'http://localhost:7071/api' }]
})

writeFileSync(join(__dirname, '..', 'openapi.json'), `${JSON.stringify(document, null, 2)}\n`)
